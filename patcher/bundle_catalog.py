"""Generate feature/setting admission from the existing recipe ownership catalog."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def plan(catalog=None):
    from features import FEATURES
    import recipe_catalog
    profile = json.loads((ROOT / 'bundle-profile.json').read_text())
    supported = set(profile['default_enabled']) | set(profile['optional_features'])
    if supported - set(FEATURES) or not set(profile['forced_features']) <= set(profile['default_enabled']):
        raise ValueError('Unknown or inconsistent bundle features')
    catalog = catalog or recipe_catalog.extract()
    if catalog['unresolved']:
        raise ValueError('Unresolved source declarations')
    # Core infrastructure is necessary for player ownership and shared controls.
    admitted = [c['id'] for c in catalog['contracts']
                if set(c['features']) & (supported | {'core'})]
    return dict(profile=profile, supported=sorted(supported),
                settings=sorted((supported - set(profile['forced_features'])) | set(profile['settings'])),
                contracts=sorted(admitted), hook_contracts=sorted(c['id'] for c in catalog['contracts']
                if c['hook'] and c['id'] in admitted))


def generate():
    p = plan()
    literal = lambda values: '@[' + ','.join('@' + json.dumps(v) for v in values) + ']'
    lines = ['// Generated by bundle_catalog.py from recipe ownership and bundle-profile.json.',
             '#define RV_BUNDLE_SUPPORTED ' + literal(p['supported']),
             '#define RV_BUNDLE_SETTINGS ' + literal(p['settings']),
             '#define RV_BUNDLE_FORCED ' + literal(p['profile']['forced_features']),
             '#define RV_BUNDLE_DEFAULTS ' + literal(p['profile']['default_enabled']),
             '#define RV_BUNDLE_CONTRACTS ' + literal(p['contracts']),
             '#define RV_BUNDLE_PREFERENCE_PREFIX @' + json.dumps(p['profile']['preference_prefix'])]
    (ROOT / 'native/RVBundleCatalog.h').write_bytes(('\n'.join(lines) + '\n').encode())
    return p


if __name__ == '__main__':
    p = generate()
    print(json.dumps({k: len(p[k]) for k in ['supported', 'settings', 'contracts', 'hook_contracts']}))
